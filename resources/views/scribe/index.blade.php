        <h1 id="introduction">Introduction</h1>
<p>GraphRAG Web App API - A chat platform powered by a Laravel backend with future AI microservices.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8000</code>
</aside>
<pre><code>This is the Phase 1 API for the GraphRAG web application.

Authentication uses Laravel Sanctum with two modes:
- **SPA cookie auth** for the Vue frontend (session-based)
- **Personal access tokens** for programmatic clients (Bearer header)

The chat endpoint returns placeholder responses until the AI microservices are connected in Phase 2.</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>This API is not authenticated.</p>

